def pref_from_store_name(name):
    """(都道府県, 根拠の地名) か None"""
    s = unicodedata.normalize("NFKC", name or "")
    hits = {}
    for pref, words in PLACES.items():
        for w in words:
            if w in s:
                hits.setdefault(pref, w)
    if len(hits) != 1:
        return None
    (pref, word), = hits.items()
    return pref, word
